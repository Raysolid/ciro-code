#!/usr/bin/env node
/**
 * Embed prompts/base.md and prompts/{mode}.md into generated/mode-prompts.ts.
 * Exports BASE, per-mode deltas, and combined (base ⊕ delta) for compatibility.
 * Usage: node ./scripts/embed-prompts.mjs [--check]
 */
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const MODES = ['ask', 'agent', 'plan', 'debug'];
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const promptsDir = join(root, 'prompts');
const outFile = join(root, 'generated', 'mode-prompts.ts');
const checkOnly = process.argv.includes('--check');

function escapeForTemplateLiteral(s) {
  return s.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${');
}

function readPromptMd(name) {
  const file = join(promptsDir, `${name}.md`);
  if (!existsSync(file)) {
    console.error(`[embed-prompts] missing: ${file}`);
    process.exit(1);
  }
  const text = readFileSync(file, 'utf8').trim();
  if (!text) {
    console.error(`[embed-prompts] empty: ${file}`);
    process.exit(1);
  }
  return text;
}

const base = readPromptMd('base');
const deltas = {};
const combined = {};
for (const mode of MODES) {
  deltas[mode] = readPromptMd(mode);
  combined[mode] = `${base}\n\n${deltas[mode]}`;
}

const body = `/** AUTO-GENERATED by scripts/embed-prompts.mjs — do not edit. */
export const BASE_SYSTEM_PROMPT = \`${escapeForTemplateLiteral(base)}\`;

export const MODE_DELTA_PROMPTS = {
  ask: \`${escapeForTemplateLiteral(deltas.ask)}\`,
  agent: \`${escapeForTemplateLiteral(deltas.agent)}\`,
  plan: \`${escapeForTemplateLiteral(deltas.plan)}\`,
  debug: \`${escapeForTemplateLiteral(deltas.debug)}\`,
} as const;

/** base ⊕ mode delta（兼容旧调用方） */
export const MODE_SYSTEM_PROMPTS = {
  ask: \`${escapeForTemplateLiteral(combined.ask)}\`,
  agent: \`${escapeForTemplateLiteral(combined.agent)}\`,
  plan: \`${escapeForTemplateLiteral(combined.plan)}\`,
  debug: \`${escapeForTemplateLiteral(combined.debug)}\`,
} as const;
`;

if (checkOnly) {
  if (!existsSync(outFile)) {
    console.error('[embed-prompts] --check failed: generated file missing');
    process.exit(1);
  }
  const existing = readFileSync(outFile, 'utf8');
  const a = createHash('sha256').update(existing).digest('hex');
  const b = createHash('sha256').update(body).digest('hex');
  if (a !== b) {
    console.error('[embed-prompts] --check failed: generated/mode-prompts.ts is stale; run pnpm embed');
    process.exit(1);
  }
  process.exit(0);
}

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, body, 'utf8');
console.log(`[embed-prompts] wrote ${outFile}`);
